type Key = tuple[str, str, str, str, str, str, str, str]


class R:
    def __init__(self, df: pl.DataFrame) -> None:
        self.v: dict[Key, float] = {}
        self.n: dict[Key, float] = {}
        for r in df.iter_rows(named=True):
            k: Key = (
                r["table"],
                r["variant"],
                r["rule"] or "",
                r["stop"] or "",
                r["stress"] or "",
                r["year"] or "",
                r["seed"] or "",
                r["metric"],
            )
            self.v[k] = float(r["value"])
            if r["n"] is not None:
                self.n[k] = float(r["n"])

    def get(
        self,
        table: str,
        variant: str,
        metric: str,
        rule: str = "",
        stop: str = "",
        stress: str = "",
        year: str = "pooled",
        seed: str = "",
    ) -> float:
        return self.v.get((table, variant, rule, stop, stress, year, seed, metric), math.nan)

    def cnt(
        self,
        table: str,
        variant: str,
        metric: str,
        rule: str = "",
        stop: str = "",
        stress: str = "",
        year: str = "pooled",
        seed: str = "",
    ) -> float:
        return self.n.get((table, variant, rule, stop, stress, year, seed, metric), math.nan)

    def seeds(self, table: str, variant: str) -> list[str]:
        s = {k[6] for k in self.v if k[0] == table and k[1] == variant and k[6] not in ("", "ens")}
        return sorted(s)


def pct(x: float, nd: int = 1) -> str:
    return "n/a" if math.isnan(x) else f"{100 * x:.{nd}f}"


def pp(x: float, nd: int = 1) -> str:
    return "n/a" if math.isnan(x) else f"{100 * x:+.{nd}f}"


def num(x: float, nd: int = 0) -> str:
    return "n/a" if math.isnan(x) else f"{x:,.{nd}f}"


def table(head: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return [*out, ""]


def seed_stats(
    r: R, table_: str, variant: str, metric: str, **kw: str
) -> tuple[float, float, float]:
    """(mean over seeds, min, max); for a variant without seeds, the ensemble value three times."""
    ss = r.seeds(table_, variant)
    vals = [r.get(table_, variant, metric, seed=s, **kw) for s in ss]
    vals = [v for v in vals if not math.isnan(v)]
    if not vals:
        e = r.get(table_, variant, metric, seed="ens", **kw)
        return e, e, e
    return sum(vals) / len(vals), min(vals), max(vals)


