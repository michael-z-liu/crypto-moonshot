def seed_stats_n(r: R, v: str, top: str, year: str = "pooled") -> tuple[float, float, float]:
    ss = r.seeds("top", v)
    vals = [r.cnt("top", v, "hit10", rule=top, year=year, seed=s) for s in ss] or [
        r.cnt("top", v, "hit10", rule=top, year=year, seed="ens")
    ]
    vals = [x for x in vals if not math.isnan(x)]
    if not vals:
        return math.nan, math.nan, math.nan
    return sum(vals) / len(vals), min(vals), max(vals)


def spec_words(spec: dict[str, Any]) -> str:
    m = spec["method"]
    rule = spec["pick_rule"]
    gate = rule["gate"]
    if m["kind"] == "gbm":
        st = m["settings"]
        what = (
            f"A gradient-boosted classifier (`{spec['settings_name']}`: {st['max_iter']} iterations, "
            f"{st['max_leaf_nodes']} leaves, min {st['min_samples_leaf']} per leaf, learning rate "
            f"{st['learning_rate']}, max_features {st['max_features']}) on {len(m['features'])} "
            f"features, target hit10; score = mean probability over seeds {m['seeds']}."
        )
    else:
        t = m["transparent"]
        coins = " and ".join(f"{'low' if d < 0 else 'high'} `{f}`" for f, d in t["coin"])
        tg = t["gate"]
        days = (
            "every day"
            if tg is None
            else f"days with `{tg['factor']}` at or above its {round(100 * tg['pct'])}th "
            "percentile over the training days"
        )
        what = (
            f"The transparent rule (no model): {days}; within the day sorted on the mean "
            f"within-day rank of {coins} (score = that mean rank, 0..1)."
        )
    g = (
        ""
        if gate is None
        else f", only on days with `{gate['factor']}` at or above its training {round(100 * gate['pct'])}th percentile"
    )
    return (
        f"{what} Each day take up to {rule['k']} entries with score percentile (against the "
        f"training scores) at least {rule['q']:.2f}{g}, in score order, into the book ($10,000, "
        "10 equal slots of realised equity, one position per coin, no free slot: skipped). "
        "Primary stop 10%. Confirm period: train on all discovery at 2024-01-01, retrain on "
        "1 January 2025 and 2026 on every entry whose window has ended."
    )


def notes(r: R, led: pl.DataFrame, spec: dict[str, Any]) -> list[str]:
    out: list[str] = []
    for v in ("gbm_all", "gbm_coin", "gbm_lean"):
        aucs = [r.get("auc", v, "auc", year=y, seed=s) for y in YEARS for s in r.seeds("auc", v)]
        if aucs:
            spread = max(
                max(r.get("auc", v, "auc", year=y, seed=s) for s in r.seeds("auc", v))
                - min(r.get("auc", v, "auc", year=y, seed=s) for s in r.seeds("auc", v))
                for y in YEARS
            )
            out.append(
                f"Seed spread `{v}`: the largest per-year AUC range over seeds is {spread:.4f}."
            )
    m_auc = r.get("auc", "gbm_market", "auc", seed="ens")
    a_auc = r.get("auc", "gbm_all", "auc", seed="ens")
    out.append(
        f"Market timing: pooled AUC of the market-only model {m_auc:.3f} against {a_auc:.3f} for all factors (pooled AUC mixes years, so it also rewards the year level)."
    )
    w = r.get("when_which", "gbm_all", "when_hit10", rule="top5", seed="ens")
    wh = r.get("when_which", "gbm_all", "which_hit10", rule="top5", seed="ens")
    out.append(
        f"For `gbm_all`'s top 5%, {pp(w)} pp of the hit10 lift is *when* and {pp(wh)} pp is *which*."
    )
    return out


